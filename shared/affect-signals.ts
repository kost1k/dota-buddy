/**
 * Отображение сигналов матча на оси аффекта. Чистый модуль.
 *
 * Жёсткое условие, на котором сломался прототип: оси питаются ТОЛЬКО
 * причинно наблюдаемыми сигналами — теми, что зритель видит на экране
 * одновременно с бадди. `sweatLevel` кормился дельтами GPM, которые
 * меняются незаметно и не совпадают по времени ни с чем, и потому его
 * поведение читалось случайным.
 *
 * Отсюда же список того, чего здесь НЕТ: GPM и XPM (медленные агрегаты),
 * готовность ультимейта (единственный сигнал, требующий знания Доты),
 * плотность событий (уже учтена свежестью — класть её ещё и в ось значит
 * считать одно дважды).
 */

import type { MatchSnapshot } from './snapshot'
import { scoreLead } from './snapshot'

/**
 * Преимущество в счёте, при котором валентность выходит почти на предел.
 *
 * Мягкое насыщение через гиперболический тангенс: разрыв в тридцать килов
 * не должен ощущаться втрое сильнее разрыва в десять — к этому моменту
 * всё уже ясно.
 */
const LEAD_SCALE = 12

/** Потолок основы: остаток шкалы оставлен смещению от событий. */
const BASE_VALENCE_LIMIT = 0.75

/**
 * Время, за которое накопленный урон спадает до ~37%.
 *
 * Это ширина окна «недавно»: пять секунд — характерная длительность
 * размена, после которого либо всё кончилось, либо уже идёт замес.
 */
const DAMAGE_TAU = 5

/**
 * Накопленный урон, дающий полное возбуждение: доля максимального
 * здоровья, потерянная за окно.
 *
 * Выбрано по записи живого матча, а не на глаз: при этом значении среднее
 * возбуждение в замесе выходит 0.37 против 0.04 в тишине.
 */
const FULL_DAMAGE = 0.35

/**
 * Мёртвая зона у нуля, в долях шкалы урона.
 *
 * Без неё хвост затухания держал бы бадди чуть шевелящимся всё время, а в
 * покое амплитуда обязана быть РОВНО нулём (`motion.ts`): движущиеся
 * стимулы перехватывают внимание и раздражают, и платить эту цену в покое
 * не за что. Измерено: порог даёт половину всего выигрыша по покою.
 */
const DAMAGE_KNEE = 0.15

/** Вклад обездвиживающих состояний и прочих дебаффов. */
const DISABLE_AROUSAL = 0.5
const DEBUFF_AROUSAL = 0.25

/** Вклад низкого здоровья. Квадратично — заметен только у самой грани. */
const LOW_HEALTH_AROUSAL = 0.4

function clamp(value: number, min: number, max: number): number {
  return Math.min(Math.max(value, min), max)
}

/**
 * Медленная основа валентности: преимущество в счёте.
 *
 * Счёт — единственный кросс-командный сигнал в снапшоте: чужих состояний
 * обычный матч не отдаёт. Он же и подходит по темпу — меняется редко и
 * отражает «как вообще идут дела», а валентность обязана дрейфовать, а не
 * прыгать.
 *
 * События всей игры GSI отдаёт (измерено 2026-09-20), и из них со временем
 * может выйти более быстрая основа. Но это отдельный источник со
 * скользящим окном и дедупликацией — заводить его надо осознанно, а не
 * подмешивать сюда.
 *
 * Доля здоровья сюда НЕ идёт: она возвращается к единице за десятки секунд
 * и шумела бы на медленной оси.
 */
export function baseValence(snapshot: MatchSnapshot): number {
  return Math.tanh(scoreLead(snapshot) / LEAD_SCALE) * BASE_VALENCE_LIMIT
}

/**
 * Накопленный урон: сколько здоровья потеряно за недавнее окно.
 *
 * Здесь урон ИНТЕГРИРУЕТСЯ, а не дифференцируется, и это главное отличие
 * от прежней конструкции. Раньше бралась мгновенная скорость потери за
 * один межпакетный интервал — то есть производная сигнала с каденцией
 * 1 Гц, а такая производная по построению усиливает шум: одиночный размен
 * давал выброс на один снапшот и мгновенный возврат к нулю. Измерено на
 * записи живого матча: 8.2 разворота движения в минуту, бадди трясло всю
 * игру.
 *
 * Накопитель превращает череду толчков в один подъём с плавным спадом.
 * Решение тикета 09 «скорость, а не уровень» при этом сохраняется:
 * запас с затуханием и есть сглаженная скорость, просто посчитанная
 * интегрированием.
 *
 * Лечение запас не опустошает — только затухание. Иначе хилка обрывала бы
 * тревогу мгновенно, хотя по ощущению напряжение спадает постепенно.
 *
 * @param accumulated запас на предыдущем шаге
 * @param previous предыдущий снапшот; `null` — считаем, что урона не было
 * @param next текущий снапшот
 * @param elapsedSeconds время между снапшотами
 */
export function accumulateDamage(
  accumulated: number,
  previous: MatchSnapshot | null,
  next: MatchSnapshot,
  elapsedSeconds: number,
): number {
  const current = Number.isFinite(accumulated) ? Math.max(accumulated, 0) : 0
  if (!Number.isFinite(elapsedSeconds) || elapsedSeconds <= 0)
    return current

  // Экспоненциально, как и всё остальное в проекте: только так результат
  // не зависит от того, как часто вызывали, а каденция GSI плавает.
  const decayed = current * Math.exp(-elapsedSeconds / DAMAGE_TAU)

  const lost = previous ? previous.hero.healthFraction - next.hero.healthFraction : 0
  return decayed + Math.max(lost, 0)
}

/**
 * Основа возбуждения: недавний урон, дебаффы и остаток здоровья.
 *
 * Функция от СОСТОЯНИЯ, без времени: всё временное живёт в накопителе.
 * Так проверяется каждая часть отдельно, и так же устроена `baseValence`.
 *
 * `has_debuff` в оси НЕ участвует, хотя тикет 09 включал дебаффы с
 * обоснованием «краткие, наблюдаемые, означают сейчас решается». Для
 * именованных флагов это верно: `stunned` занимает 0.8% матча. Для
 * `has_debuff` измерение дало 22% матча и 90 переключений — он истинен
 * при любом отрицательном модификаторе, вплоть до замедления от крипа, и
 * посылка тикета к нему не относится. Он не тряс бадди, он не давал ему
 * останавливаться.
 *
 * @param snapshot текущий снапшот
 * @param accumulatedDamage запас из `accumulateDamage`
 */
export function baseArousal(snapshot: MatchSnapshot, accumulatedDamage: number): number {
  const hero = snapshot.hero

  const filled = clamp(accumulatedDamage / FULL_DAMAGE, 0, 1)
  // Мёртвая зона: ниже порога вклад ровно ноль, выше — остаток шкалы
  // растягивается на весь диапазон, чтобы порог не съедал амплитуду.
  const damage = Math.max(0, (filled - DAMAGE_KNEE) / (1 - DAMAGE_KNEE))

  // Обездвиживающие состояния и прочие дебаффы не складываются между собой:
  // два дебаффа разом не вдвое тревожнее одного, и бюджет оси тратить на
  // это незачем.
  const disabled = hero.stunned || hero.hexed
  const status = disabled ? DISABLE_AROUSAL : (hero.silenced ? DEBUFF_AROUSAL : 0)

  const lowHealth = hero.alive
    ? (1 - hero.healthFraction) ** 2 * LOW_HEALTH_AROUSAL
    : 0

  return clamp(damage + status + lowHealth, 0, 1)
}
