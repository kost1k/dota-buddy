/**
 * Общие параметры движения для всех визуалов. Чистый модуль.
 *
 * Числа здесь взяты из разведки, а не подобраны на глаз
 * (`docs/research/shape-motion-perception.md`), и потому закреплены
 * тестами: их легко «поправить по вкусу», не заметив, что они на чём-то
 * стоят.
 *
 * Ключевой факт, определяющий всё остальное: ускорение -> возбуждение это
 * лучшее отображение «движение -> аффект» в литературе (ηp² = .870), а
 * ускорение -> валентность — чистый ноль (p = .478). Поэтому движение у
 * всех визуалов ведёт ТОЛЬКО возбуждение, а валентность каждый визуал
 * несёт по-своему.
 */

/**
 * Частота дыхания. Взята из физиологии покоя и стресса, а не назначена:
 * 10-14 вдохов/мин в глубоком покое, 30-40 в ажитации — чистый трёхкратный
 * размах.
 */
export const BREATH_HZ = { calm: 0.17, agitated: 0.5 } as const

/**
 * Потолок любых колебаний. Выше ~10 Гц движение читается электронным, а не
 * взволнованным: в спектре реального движения запястья, даже гневного, нет
 * заметных составляющих выше этой границы.
 */
export const MAX_OSCILLATION_HZ = 10

/**
 * Доля тела, на которую дышит бадди на пике возбуждения.
 *
 * Физиологическая экскурсия грудной клетки — 1-4% размера тела, то есть
 * 1.4-5.4 px при теле в 135 px. Это ниже порога различения при 0.94° и
 * добивается сжатием потока, поэтому амплитуду преувеличиваем в 2-4 раза.
 */
const BREATH_AMPLITUDE_PEAK = 0.09

function clamp01(value: number): number {
  return Number.isFinite(value) ? Math.min(Math.max(value, 0), 1) : 0
}

/** @param arousal 0..1 */
export function breathHz(arousal: number): number {
  const a = clamp01(arousal)
  return BREATH_HZ.calm + a * (BREATH_HZ.agitated - BREATH_HZ.calm)
}

/**
 * Амплитуда дыхания в тех же единицах, что `bodySize`.
 *
 * В покое ровно ноль, а не малый постоянный пол: движущиеся стимулы
 * перехватывают внимание и раздражают, и в покое платить эту цену не за
 * что.
 */
export function breathAmplitude(arousal: number, bodySize: number): number {
  return clamp01(arousal) * BREATH_AMPLITUDE_PEAK * bodySize
}

/**
 * Профиль минимального рывка: `10τ³ − 15τ⁴ + 6τ⁵`.
 *
 * Это спокойный пол движения. Ажитация выражается как отклонение от него —
 * тогда не нужно держать два набора анимаций и переключаться между ними,
 * что дало бы щелчок вместо непрерывности (ADR-0001).
 */
export function minJerk(tau: number): number {
  if (!Number.isFinite(tau))
    return 0
  const t = Math.min(Math.max(tau, 0), 1)
  return t * t * t * (10 + t * (-15 + 6 * t))
}
