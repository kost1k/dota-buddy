/**
 * Контракт визуала.
 *
 * Визуал — одна из взаимозаменяемых форм бадди. Он получает ровно этот
 * набор и не знает больше ничего: ни про WebSocket, ни про снапшоты, ни про
 * периферию.
 *
 * Смысл контракта — в том, чтобы новая фича добавлялась ОДИН раз, а не
 * умножалась на число визуалов. Без него пятый визуал обошёлся бы впятеро
 * дороже первого, и фичи перестали бы добавляться.
 *
 * Каналы перечислены здесь намеренно и исчерпывающе: сколько каналов
 * объект в 135 px вообще выдерживает — предмет разведки, а не вкуса.
 * Ответ: ДВА раздельных на две оси, всё остальное обязано быть избыточным
 * (`docs/research/shape-motion-perception.md`).
 */

import type { AffectState } from './affect'
import type { BuddyEvent } from './events'
import type { Milestones } from './milestones'

export interface VisualProps {
  /** −1..1, медленная ось. Состояние, без импульса. */
  valence: number
  /** 0..1, быстрая ось. Состояние, без импульса. */
  arousal: number
  /**
   * Быстрый слой поверх состояния: рывок от события, затухающий за доли
   * секунды.
   *
   * Отдельно от состояния он живёт вынужденно. Событие по-настоящему
   * меняет ход матча и должно сдвинуть ЦЕЛЬ аффекта — медленно и надолго.
   * Но рывок обязан уложиться в 100-200 мс, а постоянная времени
   * валентности — двенадцать секунд. Одним механизмом это не сделать.
   *
   * Визуал складывает его с состоянием для базовой отрисовки и может
   * использовать отдельно — например, чтобы выбрать профиль движения.
   */
  impulse: AffectState
  /**
   * Необратимые достижения матча: аганим и шард, каждый со своим
   * элементом.
   */
  milestones: Milestones
  /**
   * Уровень героя, 0 если неизвестен.
   *
   * Непрерывная подложка долгой дуги: обе оси аффекта возвратны, вех всего
   * две и обе необязательные, так что без уровня сорокаминутный матч не
   * имел бы видимого развития. Влияние должно быть медленным и негромким —
   * это не третий канал аффекта, а другое измерение времени.
   */
  level: number
  /**
   * Последнее сработавшее событие. Меняет `id` при каждом срабатывании —
   * по этому визуал и понимает, что пора выбрать новый профиль движения.
   */
  event: BuddyEvent | null
  /** Режим сна: вне матча. */
  asleep: boolean
}

export type VisualId
  = | 'eye'
    | 'supershape'
    | 'torus'
    | 'metaballs'
    | 'crystal'
    | 'breath'

export interface VisualMeta {
  label: string
  /** Семейство формы — главное, чем визуалы различаются. */
  form: string
  /** Чем этот визуал несёт валентность. */
  valenceCarrier: string
}

/**
 * Возбуждение у всех визуалов одинаковое: темп и амплитуда движения плюс
 * теплота тона. Это не экономия, а следствие замера — ускорение на
 * возбуждение это лучшее отображение «движение → аффект» в литературе
 * (ηp² = .870), тогда как ускорение на валентность — чистый ноль.
 *
 * Поэтому различаются они формой и носителем валентности.
 */
export const VISUALS: Record<VisualId, VisualMeta> = {
  eye: {
    label: 'Глаз',
    form: 'сфера с глазом',
    valenceCarrier: 'геометрия век, светлота',
  },
  supershape: {
    label: 'Супершейп',
    form: 'суперформула Гилиса',
    valenceCarrier: 'показатели формы: округлость ↔ шипы',
  },
  torus: {
    label: 'Кольцо',
    form: 'тор, дыра в силуэте',
    valenceCarrier: 'рябь поверхности; возбуждение добавляет дрожь',
  },
  metaballs: {
    label: 'Метасферы',
    form: 'слипающиеся доли, поле',
    valenceCarrier: 'связность: слияние ↔ распад',
  },
  crystal: {
    label: 'Кристалл',
    form: 'выпуклая оболочка, плоские грани',
    valenceCarrier: 'радиусы вершин: собранность ↔ осколок',
  },
}

/**
 * Основной визуал. По решению о ярусах поддержки (спека, §2.6) именно он
 * получает эскалацию, вехи и всё последующее; остальные подтягиваются,
 * только когда данные покажут, что они того стоят.
 */
export const DEFAULT_VISUAL: VisualId = 'torus'

export function isVisualId(value: unknown): value is VisualId {
  return typeof value === 'string' && value in VISUALS
}
