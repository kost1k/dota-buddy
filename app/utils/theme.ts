/**
 * Визуальные константы оверлея — единственное место, где они живут.
 *
 * Разбрасывать цвета и тайминги по стилям нельзя: при переходе к раздаче
 * (темы, пресеты) их придётся собирать обратно, а при калибровке — искать.
 * Значения отсюда одновременно уходят в CSS-переменные (см. `app.vue`) и в
 * материалы сцены.
 */

export const theme = {
  scene: {
    /**
     * Буфер рендера считается в CSS-пикселях, а не в физических.
     * В эфире OBS рисует 1:1, поэтому Retina-буфер — это четырёхкратная
     * плата за качество, которого зритель не увидит. Побочно удобно:
     * в браузере на машине разработки картинка выглядит ровно так же,
     * как будет выглядеть в стриме.
     */
    dpr: 1,
    /** Частота кадров в состоянии сна. Бадди жив, но почти ничего не стоит. */
    sleepFps: 12,
    /** Сторона сцены в CSS-пикселях при выводе в 1080p. */
    size: 320,
  },

  /**
   * Якорь оверлея: отступы от правого и нижнего края кадра.
   *
   * Опорная зона — правый край выше окна тайника: центр кадра принадлежит
   * игре. Подобрано по реальному кадру 1920x1080 (см. тикет 02): силуэт
   * бадди выходит примерно на y 583..718, то есть отрывается от панели
   * тайника (её верх на y≈878) и не залезает в середину экрана, где идёт
   * игра.
   *
   * Пресеты позиций через ?pos= — рубеж 3; пока якорь один.
   */
  anchor: {
    right: 44,
    bottom: 270,
  },

  color: {
    /**
     * Валентность кодируется температурой и насыщенностью, а не парой
     * «зелёный ↔ красный»: та читается как индикатор, а не как существо,
     * и отваливается у дальтоников (см. спеку, §2.3).
     */
    /*
     * Светлота концов шкалы выровнена намеренно (обе ~155 по Rec.709).
     * Первая редакция брала тёмно-синий #2f5d7c с яркостью 86, и при низкой
     * валентности бадди пропадал на тёмной карте. Решение было — кодировать
     * валентность ТЕМПЕРАТУРОЙ И НАСЫЩЕННОСТЬЮ, а не яркостью; яркость
     * должна остаться свободной для других нужд.
     */
    valenceLow: '#6aa3c4',
    valenceHigh: '#e0912f',

    surface: '#06090c',
    ink: '#c8d2d8',
    inkMuted: '#5d6a71',
  },

  /**
   * Существо. Всё непрозрачное: ADR-0003 запрещает частичную альфу как
   * несущий приём, и это касается орбит тоже — в прототипе они шли на
   * `opacity: 0.8`.
   */
  creature: {
    /** Тёплая кость, не белая: чистый белый на маленьком силуэте слепит. */
    sclera: '#e9dfcb',
    iris: '#14181d',
    highlight: '#fffaf0',
    /** Множитель к цвету тела для орбит. */
    orbitShade: 0.72,
  },

  /**
   * Края чёткие, теней и растушёвки нет — ADR-0003: открытые баги альфы в
   * obs-browser делают мягкие края грязными в эфире.
   */
  edge: {
    width: '1px',
    radius: '4px',
  },

  motion: {
    /** Длительность появления и исчезновения периферийных элементов. */
    fadeMs: 180,
  },
} as const

/** Токены в виде CSS-переменных — чтобы стили и сцена брали один источник. */
export function themeCssVars(): Record<string, string> {
  return {
    '--db-valence-low': theme.color.valenceLow,
    '--db-valence-high': theme.color.valenceHigh,
    '--db-surface': theme.color.surface,
    '--db-ink': theme.color.ink,
    '--db-ink-muted': theme.color.inkMuted,
    '--db-edge-width': theme.edge.width,
    '--db-edge-radius': theme.edge.radius,
    '--db-fade': `${theme.motion.fadeMs}ms`,
    '--db-scene-size': `${theme.scene.size}px`,
    '--db-anchor-right': `${theme.anchor.right}px`,
    '--db-anchor-bottom': `${theme.anchor.bottom}px`,
  }
}
